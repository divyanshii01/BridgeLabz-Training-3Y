public class Double {
    public static void main(String[] args) {
        double a = 5.5, b = 2.2, c = 3.3;

        double op1 = a + b * c;
        double op2 = a * b + c;
        double op3 = c + a / b;
        double op4 = a % b + c;

        System.out.println("The results of Double Operations are " + op1 + ", " + op2 + ", " + op3 + ", " + op4);
    }
}
