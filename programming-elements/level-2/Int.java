public class Int {
    public static void main(String[] args) {
        int a = 5, b = 2, c = 3;

        int op1 = a + b * c;
        int op2 = a * b + c;
        int op3 = c + a / b;
        int op4 = a % b + c;

        System.out.println("The results of Int Operations are " + op1 + ", " + op2 + ", " + op3 + ", " + op4);
    }
}
